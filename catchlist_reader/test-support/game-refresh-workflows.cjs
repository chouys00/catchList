const { app, BrowserWindow, ipcMain, session } = require("electron");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const assert = require("node:assert/strict");
const { pathToFileURL } = require("node:url");
const root = path.resolve(__dirname, "..");
const temp = fs.mkdtempSync(path.join(os.tmpdir(), "catchlist-refresh-ui-"));
app.setPath("userData", path.join(temp, "profile"));
const deadline = setTimeout(() => { console.error("更新互動測試逾時"); app.exit(1); }, 55000);
app.whenReady().then(async () => {
  const lib = await import(pathToFileURL(path.join(root, "src/library.js")));
  const { GameRefreshService } = await import(pathToFileURL(path.join(root, "src/game-refresh-service.js")));
  const fixture = fs.readFileSync(path.join(root, "test-data/steam-tags-2026-02/遊戲.md"), "utf8")
    .replace("**HER TREES : PUZZLE DREAM** (HER TREES : PUZZLE DREAM)", "**吸血鬼爬行者：屠戮地牢的吸血鬼倖存者** (Vampire Crawlers: The Turbo Wildcard from Vampire Survivors)");
  fs.writeFileSync(path.join(temp, "遊戲.md"), fixture);
  let calls = 0; let fail = false;
  const service = new GameRefreshService({ now: () => Date.now() + calls * 2000, lookup: async () => {
    calls++; await new Promise(resolve => setTimeout(resolve, 350));
    if (fail) throw new Error("Steam 暫時限制請求，請稍後重試");
    return { score: 84, reviews: 98765, tags: ["探索", "冒險", "單人"] };
  } });
  const snapshot = () => ({ dataDir: temp, appVersion: "test", libraries: lib.loadAllLibraries(temp), hiddenEntries: lib.loadHiddenEntries(temp) });
  ipcMain.handle("library:load", snapshot);
  ipcMain.handle("library:resolve-game-covers", () => ({}));
  ipcMain.handle("games:refresh", async (_, appid) => { await service.refresh(temp, appid); return snapshot(); });
  session.defaultSession.webRequest.onBeforeRequest({ urls: ["https://*/*", "http://*/*"] }, (_, callback) => callback({ cancel: true }));
  const win = new BrowserWindow({ show: false, width: 1440, height: 1000, webPreferences: { preload: path.join(root, "src/preload.cjs"), contextIsolation: true, sandbox: true, backgroundThrottling: false } });
  const js = code => win.webContents.executeJavaScript(code);
  const until = async code => { for (let i = 0; i < 160; i++) { if (await js(code)) return; await new Promise(resolve => setTimeout(resolve, 25)); } throw new Error(`等待畫面逾時：${code}`); };
  const capture = async name => {
    if (!process.env.CATCHLIST_QA_DIR) return;
    win.showInactive();
    await new Promise(resolve => setTimeout(resolve, 200));
    fs.mkdirSync(process.env.CATCHLIST_QA_DIR, { recursive: true });
    fs.writeFileSync(path.join(process.env.CATCHLIST_QA_DIR, `${name}.png`), (await win.webContents.capturePage()).toPNG());
  };
  await win.loadFile(path.join(root, "src/renderer/index.html"));
  await until('document.querySelectorAll("[data-refresh-game]").length > 0');
  const id = await js('document.querySelector("[data-refresh-game]").dataset.refreshGame');
  assert.deepEqual(await js(`Array.from(document.querySelectorAll('.item.games .game-management')[0].children, button => button.dataset.favoriteKind || (button.hasAttribute('data-hide') ? 'hide' : button.hasAttribute('data-refresh-game') ? 'refresh' : 'delete'))`), ["personal", "shared", "hide", "refresh", "delete"]);
  const density = [];
  for (const width of [1440, 390]) {
    win.setSize(width, 1000); await new Promise(resolve => setTimeout(resolve, 200));
    const bounds = await js(`(() => { const r = document.querySelector('[data-refresh-game]').getBoundingClientRect(); return { x: r.x, right: r.right, height: r.height, width: innerWidth, overflow: document.documentElement.scrollWidth > innerWidth }; })()`);
    assert.ok(bounds.x >= 0 && bounds.right <= bounds.width && bounds.height >= 24 && !bounds.overflow, JSON.stringify(bounds));
    const layout = await js(`(() => {
      const row = document.querySelector('.item.games');
      const title = row.querySelector('.game-title-cell');
      const refresh = row.querySelector('[data-refresh-game]');
      const original = row.querySelector('.game-title-cell > small');
      const management = refresh.closest('.game-management');
      const compact = row.getBoundingClientRect().height;
      const buttons = [...management.querySelectorAll('button')];
      const result = { compact, inTitle: !!refresh.closest('.game-title-cell'), inManagement: !!management, iconOnly: refresh.textContent.trim() === '', overlap: buttons.some((button, index) => index && buttons[index - 1].getBoundingClientRect().right > button.getBoundingClientRect().left), managementFits: buttons.every(button => button.getBoundingClientRect().left >= row.getBoundingClientRect().left && button.getBoundingClientRect().right <= row.getBoundingClientRect().right) };
      const markup = title.innerHTML;
      const oldTools = document.createElement('div'); oldTools.style.marginTop = '8px';
      oldTools.innerHTML = '<button style="min-height:32px;padding:4px 8px;font-size:12px">⟳ 更新資訊</button>';
      original.after(oldTools);
      result.previous = row.getBoundingClientRect().height;
      title.innerHTML = markup;
      return result;
    })()`);
    assert.equal(layout.inTitle, false); assert.equal(layout.inManagement, true); assert.equal(layout.iconOnly, true); assert.equal(layout.overlap, false); assert.equal(layout.managementFits, true);
    assert.ok(layout.compact < layout.previous, JSON.stringify({ width, ...layout }));
    density.push({ width, ...layout });
    await capture(`refresh-${width}-idle`);
  }
  if (process.env.CATCHLIST_QA_DIR) fs.writeFileSync(path.join(process.env.CATCHLIST_QA_DIR, "layout-metrics.json"), JSON.stringify(density, null, 2));
  const idleHeight = await js('document.querySelector(".item.games").getBoundingClientRect().height');
  await js('document.querySelector("[data-refresh-game]").focus(); document.querySelector("[data-refresh-game]").click()');
  await until('document.querySelector("[data-refresh-game]").disabled');
  assert.equal(await js('document.querySelector("[data-refresh-game]").getAttribute("aria-busy")'), "true");
  assert.equal(await js('document.querySelector(".item.games").getBoundingClientRect().height'), idleHeight);
  await capture("refresh-loading");
  await js('document.querySelector("[data-refresh-game]").click()');
  await until('document.querySelector("#toast").textContent.includes("已更新遊戲")');
  assert.equal(calls, 1);
  const updated = lib.loadLibrary(temp, "games").entries.find(e => e.appid === id);
  assert.equal(updated.reviews, 98765);
  assert.equal(await js(`document.querySelector('[data-game-row="${id}"]').textContent.includes('84%')`), true);
  assert.equal(await js(`document.querySelector('[data-game-row="${id}"]').textContent.includes('98,765')`), true);
  assert.equal(await js(`document.querySelector('[data-game-row="${id}"] .game-tag').textContent`), "探索");
  assert.equal(await js(`!!document.querySelector('[data-refresh-game][title*="上次更新"]')`), true);
  await capture("refresh-success-mobile");
  win.setSize(1440, 1000); await new Promise(resolve => setTimeout(resolve, 200));
  await capture("refresh-success-desktop");
  fail = true;
  const previous = fs.readFileSync(path.join(temp, ".catchlist-game-refresh.json"), "utf8");
  await js(`document.querySelector('[data-refresh-game="${id}"]').click()`);
  await until('document.querySelector("#toast").textContent.includes("更新失敗")');
  assert.equal(fs.readFileSync(path.join(temp, ".catchlist-game-refresh.json"), "utf8"), previous);
  assert.equal(await js(`document.querySelector('[data-refresh-game="${id}"]').disabled`), false);
  assert.equal(fs.readFileSync(path.join(temp, "遊戲.md"), "utf8"), fixture);
  await win.reload();
  await until(`!!document.querySelector('[data-refresh-game][title*="上次更新"]')`);
  console.log(JSON.stringify({ success: true, widths: [1440, 390], reportUnchanged: true, persistence: true, density }));
  clearTimeout(deadline); win.destroy(); app.exit(0);
}).catch(error => { console.error(error); clearTimeout(deadline); app.exit(1); });
